function staggerIn(nodes) {
  if (window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  nodes.forEach((n, i) => {
    n.style.animationDelay = `${Math.min(i * 38, 360)}ms`;
    n.classList.add('enter');
    n.addEventListener('animationend', () => { n.classList.remove('enter'); n.style.animationDelay = ''; }, { once: true });
  });
}

/* ---- Modal infrastructure (single reusable modal) ---- */
let lastFocused = null;
function openModal({ title, body, footer, size = 'md' }) {
  const root = $('#modal');
  if (!root) return;
  lastFocused = document.activeElement;
  root.innerHTML = `
    <div class="modal__backdrop" data-close-modal></div>
    <div class="modal__dialog modal__dialog--${size}" role="dialog" aria-modal="true" aria-label="${escapeHtml(title)}">
      <div class="modal__head">
        <h2 class="modal__title">${escapeHtml(title)}</h2>
        <button class="icon-btn" data-close-modal aria-label="Close dialog">${ICONS.x}</button>
      </div>
      <div class="modal__body">${body}</div>
      <div class="modal__foot">${footer || ''}</div>
    </div>`;
  root.classList.add('is-open');
  document.body.classList.add('no-scroll');
  // focus first focusable
  requestAnimationFrame(() => {
    const f = root.querySelector('input, select, textarea, button:not([data-close-modal])') || root.querySelector('[data-close-modal]');
    if (f) f.focus();
  });
}
function closeModal() {
  const root = $('#modal');
  if (!root || !root.classList.contains('is-open')) return;
  root.classList.remove('is-open');
  root.innerHTML = '';
  document.body.classList.remove('no-scroll');
  cookState = null;
  if (lastFocused && document.contains(lastFocused)) lastFocused.focus();
}

/* ---- Drawer (shopping) ---- */
function openDrawer() {
  const root = $('#drawer');
  if (!root) return;
  lastFocused = document.activeElement;
  renderShopping();
  root.classList.add('is-open');
  root.setAttribute('aria-hidden', 'false');
  document.body.classList.add('no-scroll');
  requestAnimationFrame(() => {
    const f = root.querySelector('button:not([data-close-drawer]), input');
    if (f) f.focus(); else $('#drawer-close')?.focus();
  });
}
function closeDrawer() {
  const root = $('#drawer');
  if (!root || !root.classList.contains('is-open')) return;
  root.classList.remove('is-open');
  root.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('no-scroll');
  if (lastFocused && document.contains(lastFocused)) lastFocused.focus();
}

/* ---- Confirm dialog (promise-based, reuses modal) ---- */
function confirmDialog({ title, message, confirmLabel = 'Confirm', cancelLabel = 'Cancel', danger = false }) {
  return new Promise((resolve) => {
    const body = `<p class="confirm__msg">${message}</p>`;
    const footer = `
      <button class="btn btn--ghost" data-confirm="no">${escapeHtml(cancelLabel)}</button>
      <button class="btn ${danger ? 'btn--danger' : 'btn--primary'}" data-confirm="yes">${escapeHtml(confirmLabel)}</button>`;
    openModal({ title, body, footer, size: 'sm' });
    const root = $('#modal');
    const handler = (e) => {
      const t = e.target.closest('[data-confirm]');
      if (!t) return;
      root.removeEventListener('click', handler);
      const yes = t.dataset.confirm === 'yes';
      closeModal();
      resolve(yes);
    };
    root.addEventListener('click', handler);
    // resolve(false) if closed by backdrop/esc
    root._confirmResolve = () => resolve(false);
  });
}

/* Focus trap + ESC for modal & drawer */
function trapFocus(e) {
  const modal = $('#modal');
  const drawer = $('#drawer');
  const active = modal && modal.classList.contains('is-open') ? modal
    : drawer && drawer.classList.contains('is-open') ? drawer : null;
  if (!active) return;

  if (e.key === 'Escape') {
    if (active === modal) { if (modal._confirmResolve) { const r = modal._confirmResolve; modal._confirmResolve = null; r(); } closeModal(); }
    else closeDrawer();
    return;
  }
  if (e.key !== 'Tab') return;
  const focusables = $$('a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])', active)
    .filter((el) => el.offsetParent !== null || el === document.activeElement);
  if (!focusables.length) return;
  const first = focusables[0];
  const last = focusables[focusables.length - 1];
  if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
  else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
}

/* ============================================================================
   TABS / ROUTER
   ========================================================================== */
function switchTab(tab) {
  ui.tab = tab;
  $$('.nav__tab').forEach((b) => {
    const active = b.dataset.tab === tab;
    b.classList.toggle('is-active', active);
    b.setAttribute('aria-selected', active ? 'true' : 'false');
  });
  $$('.view').forEach((v) => v.classList.toggle('is-active', v.id === `view-${tab}`));
  if (tab === 'pantry') renderPantry();
  else if (tab === 'recipes') renderRecipes();
  else if (tab === 'stats') renderStats();
  // move keyboard focus to the panel heading region for screen-reader context
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function renderAll() {
  renderPantry();
  renderRecipes();
  renderStats();
  // ensure only active view is shown
  $$('.view').forEach((v) => v.classList.toggle('is-active', v.id === `view-${ui.tab}`));
}

/* Update the shopping count badges in header + recipes toolbar. */
