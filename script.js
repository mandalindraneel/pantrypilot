function kpiCard(label, value, sub, tone) {
  return `
    <div class="kpi ${tone ? `kpi--${tone}` : ''}">
      <span class="kpi__label">${label}</span>
      <span class="kpi__value">${value}</span>
      <span class="kpi__sub">${sub}</span>
    </div>`;
}
function deltaText(delta) {
  if (delta === null) return 'no prior month';
  if (delta === 0) return 'flat vs last month';
  return `${delta > 0 ? '▲' : '▼'} ${Math.abs(delta)}% vs last month`;
}
function deltaTone(delta) {
  if (delta === null || delta === 0) return '';
  return delta > 0 ? 'warn' : 'good';
}

/* Build weekly buckets (last 8 weeks incl. current) and draw an SVG area chart. */
function weeklyWasteBuckets(weeks = 8) {
  const today = startOfDay();
  // anchor to the start of the current week (Monday)
  const dow = (today.getDay() + 6) % 7; // 0 = Monday
  const weekStart = addDays(today, -dow);
  const buckets = [];
  for (let i = weeks - 1; i >= 0; i--) {
    const start = addDays(weekStart, -7 * i);
    const end = addDays(start, 7);
    buckets.push({ start, end, total: 0, label: fmtDate(start) });
  }
  state.waste.forEach((w) => {
    const d = parseISODate(w.date);
    if (!d) return;
    const b = buckets.find((bk) => d >= bk.start && d < bk.end);
    if (b) b.total += w.cost || 0;
  });
  return buckets;
}

function drawTrendChart() {
  const host = $('#trend-chart');
  if (!host) return;
  const data = weeklyWasteBuckets(8);
  const W = 720, H = 240;
  const padL = 44, padR = 16, padT = 18, padB = 34;
  const innerW = W - padL - padR;
  const innerH = H - padT - padB;
  const maxV = Math.max(4, Math.ceil(Math.max(...data.map((d) => d.total)) / 4) * 4);
  const x = (i) => padL + (data.length === 1 ? innerW / 2 : (innerW * i) / (data.length - 1));
  const y = (v) => padT + innerH - (v / maxV) * innerH;

  const linePts = data.map((d, i) => `${x(i).toFixed(1)},${y(d.total).toFixed(1)}`).join(' ');
  const areaPts = `${padL},${(padT + innerH).toFixed(1)} ${linePts} ${(padL + innerW).toFixed(1)},${(padT + innerH).toFixed(1)}`;

  // y gridlines / labels (5 ticks)
  const ticks = 4;
  let grid = '';
  for (let t = 0; t <= ticks; t++) {
    const v = (maxV / ticks) * t;
    const gy = y(v);
    grid += `<line class="chart__grid" x1="${padL}" x2="${padL + innerW}" y1="${gy.toFixed(1)}" y2="${gy.toFixed(1)}"/>`;
    grid += `<text class="chart__ytick" x="${padL - 8}" y="${(gy + 4).toFixed(1)}" text-anchor="end">${USD.format(v).replace('.00', '')}</text>`;
  }

  const xlabels = data.map((d, i) => `<text class="chart__xtick" x="${x(i).toFixed(1)}" y="${H - 10}" text-anchor="middle">${escapeHtml(d.label)}</text>`).join('');
  const dots = data.map((d, i) => `
    <circle class="chart__dot" cx="${x(i).toFixed(1)}" cy="${y(d.total).toFixed(1)}" r="4"
            data-i="${i}" data-label="${escapeHtml(d.label)}" data-val="${d.total.toFixed(2)}"></circle>`).join('');

  host.innerHTML = `
    <svg class="chart__svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid meet" role="img" aria-label="Weekly money wasted, last 8 weeks">
      <defs>
        <linearGradient id="areaFill" x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stop-color="var(--accent)" stop-opacity="0.28"/>
          <stop offset="100%" stop-color="var(--accent)" stop-opacity="0"/>
        </linearGradient>
      </defs>
      ${grid}
      <polygon class="chart__area" points="${areaPts}" fill="url(#areaFill)"/>
      <polyline class="chart__line" points="${linePts}" fill="none"/>
      ${dots}
      ${xlabels}
    </svg>`;

  // Hover readout
  const readout = $('#chart-readout');
  const total = data.reduce((s, d) => s + d.total, 0);
  if (readout) readout.textContent = `${USD.format(total)} over 8 weeks`;
  host.querySelectorAll('.chart__dot').forEach((dot) => {
    const show = () => {
      host.querySelectorAll('.chart__dot').forEach((d) => d.classList.remove('is-active'));
      dot.classList.add('is-active');
      if (readout) readout.textContent = `Week of ${dot.dataset.label}: ${USD.format(parseFloat(dot.dataset.val))}`;
    };
    dot.addEventListener('mouseenter', show);
    dot.addEventListener('focus', show);
    dot.setAttribute('tabindex', '0');
  });
  host.addEventListener('mouseleave', () => {
    host.querySelectorAll('.chart__dot').forEach((d) => d.classList.remove('is-active'));
    if (readout) readout.textContent = `${USD.format(total)} over 8 weeks`;
  });
}

